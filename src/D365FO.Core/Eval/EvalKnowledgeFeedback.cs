using System.Text;
using D365FO.Core.Knowledge;

namespace D365FO.Core.Eval;

/// <summary>A knowledge topic that plausibly should have prevented a case's failure, and the literal that links it.</summary>
public sealed record TopicCandidate(string TopicId, string SourcePath, string Signal);

/// <summary>
/// One proposal: a case whose runs were triaged as a knowledge problem, the
/// corpus evidence for it, and the topics an editor should look at first.
/// </summary>
public sealed record KnowledgeProposal(
    string CaseId,
    string Classification,
    int Runs,
    IReadOnlyList<string> RunIds,
    IReadOnlyList<string> Notes,
    string Instruction,
    IReadOnlyList<TopicCandidate> Candidates);

/// <summary>
/// The <c>MODEL_ERROR</c>/<c>KNOWLEDGE_GAP</c> → <c>skills/_source</c> feedback path
/// (audit finding K4; docs/AGENT_EVAL_LOOP.md §12 listed it as unbuilt).
/// </summary>
/// <remarks>
/// <para>
/// It deliberately stops at a <em>proposal</em>. The rubric puts the two classes on
/// opposite sides of the "becomes a fix?" line — a <c>KNOWLEDGE_GAP</c> means the
/// corpus taught the agent something wrong or told it nothing, and a
/// <c>MODEL_ERROR</c> means the tool was right and the agent still misused it. A
/// repeated <c>MODEL_ERROR</c> is nonetheless evidence about the corpus: the same
/// misuse across many runs usually means the guidance is easy to misread. Which of
/// the two it is, and what the topic should say instead, is a judgement this
/// command cannot make from a scorecard — so it assembles the evidence and names
/// the files, and a human or the eval-improver writes the edit.
/// </para>
/// <para>
/// Candidate topics are matched by <see cref="EvalCoverage.TopicsForCase"/>, the
/// same derivation the coverage report uses, so a case whose family no topic names
/// yields <em>no</em> candidates — which is itself the finding: the gap is a
/// missing topic, not a wrong one.
/// </para>
/// </remarks>
public static class EvalKnowledgeFeedback
{
    /// <summary>Classes that say something about the knowledge corpus rather than the code.</summary>
    public static readonly IReadOnlyList<string> FeedbackClasses = new[] { EvalTriage.KnowledgeGap, EvalTriage.ModelError };

    public static IReadOnlyList<KnowledgeProposal> Build(
        IReadOnlyList<EvalCorpusRecord> records,
        IReadOnlyList<EvalCase> cases,
        IReadOnlyList<KnowledgeTopic> topics,
        string sourceDirRelative = "skills/_source")
    {
        var byCase = cases.ToDictionary(c => c.Id, StringComparer.OrdinalIgnoreCase);

        return records
            .Where(r => r.Classification is not null
                        && FeedbackClasses.Contains(r.Classification, StringComparer.Ordinal))
            .GroupBy(r => (r.CaseId, Classification: r.Classification!), CaseClassificationComparer.Instance)
            .Select(g =>
            {
                var newestFirst = g.OrderByDescending(r => r.TimestampUtc).ToList();
                byCase.TryGetValue(g.Key.CaseId, out var @case);

                var candidates = @case is null
                    ? Array.Empty<TopicCandidate>()
                    : EvalCoverage.TopicsForCase(@case, topics)
                        .Select(h => new TopicCandidate(h.TopicId, $"{sourceDirRelative}/{h.TopicId}.md", h.Signal))
                        .ToArray();

                return new KnowledgeProposal(
                    CaseId: g.Key.CaseId,
                    Classification: g.Key.Classification,
                    Runs: newestFirst.Count,
                    RunIds: newestFirst.Take(5).Select(r => r.RunId).ToList(),
                    Notes: newestFirst
                        .Select(r => r.Note)
                        .Where(n => !string.IsNullOrWhiteSpace(n))
                        .Distinct(StringComparer.Ordinal)
                        .Take(5)
                        .ToList()!,
                    Instruction: @case?.Instruction ?? "(case not found in the catalog)",
                    Candidates: candidates);
            })
            .OrderByDescending(p => p.Runs)
            .ThenBy(p => p.CaseId, StringComparer.Ordinal)
            .ToList();
    }

    /// <summary>A review-ready brief: what failed, how often, with which topics to open first.</summary>
    public static string RenderMarkdown(IReadOnlyList<KnowledgeProposal> proposals)
    {
        var sb = new StringBuilder();
        sb.Append("# Knowledge feedback from the eval corpus\n\n");
        sb.Append("Generated by `d365fo eval knowledge`. Each entry is a *proposal*, not a change: the\n");
        sb.Append("corpus can show that a case keeps failing for a knowledge reason and which topics\n");
        sb.Append("are implicated, but what the topic should say instead is an editorial judgement.\n\n");

        if (proposals.Count == 0)
        {
            sb.Append("No `KNOWLEDGE_GAP` or `MODEL_ERROR` runs in the corpus — nothing to propose.\n");
            return sb.ToString();
        }

        foreach (var p in proposals)
        {
            sb.Append($"## `{p.CaseId}` — {p.Classification} ({p.Runs} run(s))\n\n");
            sb.Append($"> {p.Instruction}\n\n");

            if (p.Notes.Count > 0)
            {
                sb.Append("Runner notes:\n\n");
                foreach (var n in p.Notes) sb.Append($"- {n}\n");
                sb.Append('\n');
            }

            sb.Append("Evidence: ");
            sb.Append(string.Join(", ", p.RunIds.Select(r => "`" + r + "`")));
            sb.Append("\n\n");

            if (p.Candidates.Count == 0)
            {
                sb.Append("**No topic names this case's artifact types or subcommand** — the gap is a\n");
                sb.Append("missing topic, not a wrong one.\n\n");
            }
            else
            {
                sb.Append("Candidate topics:\n\n");
                foreach (var c in p.Candidates)
                    sb.Append($"- `{c.SourcePath}` — names `{c.Signal}`\n");
                sb.Append('\n');
            }
        }

        sb.Append("---\n\nAfter editing a topic, re-run `python3 scripts/emit-skills.py` so the Copilot,\n");
        sb.Append("Anthropic and CLI variants stay in sync, and `d365fo knowledge audit --verify`.\n");
        return sb.ToString();
    }

    private sealed class CaseClassificationComparer : IEqualityComparer<(string CaseId, string Classification)>
    {
        public static readonly CaseClassificationComparer Instance = new();

        public bool Equals((string CaseId, string Classification) x, (string CaseId, string Classification) y) =>
            StringComparer.OrdinalIgnoreCase.Equals(x.CaseId, y.CaseId)
            && StringComparer.Ordinal.Equals(x.Classification, y.Classification);

        public int GetHashCode((string CaseId, string Classification) obj) =>
            HashCode.Combine(
                StringComparer.OrdinalIgnoreCase.GetHashCode(obj.CaseId),
                StringComparer.Ordinal.GetHashCode(obj.Classification));
    }
}
